param([ValidateRange(1, 32)][int]$Jobs = 4, [switch]$BuildApp)
$ErrorActionPreference = 'Stop'
$coreProject = Split-Path $PSScriptRoot -Parent
$coreBase = Join-Path $coreProject 'engine/xenia'
$coreLogRoot = Join-Path $coreProject 'local/core-maintenance-20261006'
$coreSnapshot = Join-Path $coreLogRoot 'candidate'
$coreBuild = Join-Path $coreLogRoot 'jit-windows-build'
$corePatch = Join-Path $coreProject 'patches/xenia-upstream-candidates/cpu-extract-fold.patch'
$coreValueRelative = 'src/xenia/cpu/hir/value.cc'
& (Join-Path $PSScriptRoot 'prepare-core-extract-candidate.ps1')
$coreMetadata = Get-Content -LiteralPath (Join-Path $coreLogRoot 'candidate-source.json') -Raw | ConvertFrom-Json
# The rest of the fork, including existing local changes, is copied. /XO keeps
# the already verified candidate Value.cc; neither /MIR nor deletion is used.
& robocopy $coreBase $coreSnapshot /E /XO /XD .git (Join-Path $coreBase 'build') (Join-Path $coreBase 'scratch') /XF .git /NFL /NDL /NJH /NJS /NP *> (Join-Path $coreLogRoot 'snapshot-copy.log')
if ($LASTEXITCODE -ge 8) { throw 'Falló la copia aislada del core.' }
if ((Get-FileHash -LiteralPath (Join-Path $coreSnapshot $coreValueRelative)).Hash -ne $coreMetadata.candidateSha256) {
    throw 'La copia no conserva el hash del candidato auditado.'
}
& git -C $coreProject apply --directory=local/core-maintenance-20261006/candidate --reverse --check $corePatch
if ($LASTEXITCODE) { throw 'La copia no conserva la corrección esperada.' }
$coreAuditedFiles = @()
foreach ($coreFile in (& git -C $coreBase ls-files --cached --others --exclude-standard)) {
    # Shader bytecode is regenerated by the unchanged native build pipeline.
    if ($coreFile -eq $coreValueRelative -or $coreFile -match '/bytecode/') { continue }
    $coreOriginal = Join-Path $coreBase $coreFile
    if (!(Test-Path -LiteralPath $coreOriginal -PathType Leaf)) { continue }
    $coreMirror = Join-Path $coreSnapshot $coreFile
    if (!(Test-Path -LiteralPath $coreMirror -PathType Leaf)) { throw "Falta en la copia: $coreFile" }
    $coreHash = (Get-FileHash -LiteralPath $coreOriginal).Hash
    if ($coreHash -ne (Get-FileHash -LiteralPath $coreMirror).Hash) { throw "La copia diverge de la fuente activa: $coreFile" }
    $coreAuditedFiles += [ordered]@{ path = $coreFile; sha256 = $coreHash }
}
$coreAuditedFiles | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath (Join-Path $coreLogRoot 'snapshot-sources.json') -Encoding utf8
& git -C $coreBase submodule status --recursive | Set-Content -LiteralPath (Join-Path $coreLogRoot 'snapshot-dependencies.log') -Encoding utf8
if ($LASTEXITCODE) { throw 'No se pudo registrar la revisión de dependencias.' }
foreach ($coreTest in @('extract_fold_contract_test.cc', 'emulos_app_flags_test.cc')) {
    Copy-Item -LiteralPath (Join-Path $coreProject "tests/core-semantics/$coreTest") -Destination (Join-Path $coreSnapshot "src/xenia/cpu/testing/$coreTest")
}
$coreGitDirectory = (& git -C $coreBase rev-parse --absolute-git-dir).Trim()
$coreGitAlias = Join-Path $coreSnapshot '.git'
$coreGitAliasText = "gitdir: $coreGitDirectory`n"
if (Test-Path -LiteralPath $coreGitAlias) {
    if ((Get-Item -LiteralPath $coreGitAlias).PSIsContainer -or
        [IO.File]::ReadAllText($coreGitAlias) -ne $coreGitAliasText) {
        throw 'Metadatos Git ajenos en la copia. No se sobrescriben.'
    }
}
# CMake's version generator reads the true baseline HEAD through this temporary
# alias. No Git mutations are run inside the snapshot. Remove this file only,
# never the gitdir it names, when the command finishes (including failures).
[IO.File]::WriteAllText($coreGitAlias, $coreGitAliasText, [Text.UTF8Encoding]::new($false))
try {
    $vswhere = "${env:ProgramFiles(x86)}/Microsoft Visual Studio/Installer/vswhere.exe"
    $coreVsPath = & $vswhere -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if (!$coreVsPath) { throw 'Faltan las herramientas C++ de Visual Studio.' }
    Import-Module "$coreVsPath/Common7/Tools/Microsoft.VisualStudio.DevShell.dll"
    Enter-VsDevShell -VsInstallPath $coreVsPath -SkipAutomaticLocation -DevCmdArguments '-arch=x64 -host_arch=x64' | Out-Null
    $env:VSLANG = '1033'
    $env:PATH = "$coreProject/.tools/glslang/bin;$coreProject/.tools/spirv-build/tools/Release;$env:PATH"
    & cmake -S $coreSnapshot -B $coreBuild -G 'Ninja Multi-Config' -DXENIA_BUILD_TESTS=ON *> (Join-Path $coreLogRoot 'jit-configure.log')
    if ($LASTEXITCODE) { throw "Falló CMake. Ver $coreLogRoot/jit-configure.log" }
    & cmake --build $coreBuild --config Release --target xenia-cpu-tests -j $Jobs *> (Join-Path $coreLogRoot 'jit-build.log')
    if ($LASTEXITCODE) { throw "Falló el enlace de tests. Ver $coreLogRoot/jit-build.log" }
    $coreExecutable = Join-Path $coreBuild 'bin/Windows/Release/xenia-cpu-tests.exe'
    Push-Location $coreLogRoot
    try {
        & $coreExecutable '[emulos-extract]' --reporter compact *> (Join-Path $coreLogRoot 'jit-extract-tests.log')
        if ($LASTEXITCODE) { throw 'Falló la prueba diferencial del JIT.' }
        & $coreExecutable --reporter compact *> (Join-Path $coreLogRoot 'jit-full-cpu-tests.log')
        if ($LASTEXITCODE) { throw 'Falló la batería completa de CPU. No se acepta el candidato.' }
    } finally { Pop-Location }
    if ($BuildApp) {
        & cmake --build $coreBuild --config Release --target xenia-app -j $Jobs *> (Join-Path $coreLogRoot 'candidate-core-build.log')
        if ($LASTEXITCODE) { throw 'Falló el enlace del emulador completo de prueba.' }
    }
    Get-Content -LiteralPath (Join-Path $coreLogRoot 'jit-extract-tests.log') -Tail 5
    Get-Content -LiteralPath (Join-Path $coreLogRoot 'jit-full-cpu-tests.log') -Tail 5
} finally {
    if (Test-Path -LiteralPath $coreGitAlias) {
        if ([IO.File]::ReadAllText($coreGitAlias) -eq $coreGitAliasText) {
            Remove-Item -LiteralPath $coreGitAlias
        }
    }
    if ((Get-FileHash -LiteralPath (Join-Path $coreBase $coreValueRelative)).Hash -ne $coreMetadata.baselineSha256) {
        throw 'La fuente activa cambió durante el proceso. Reauditar la procedencia.'
    }
}
Write-Output "Pruebas del JIT terminadas. Evidencia y artefactos: $coreLogRoot"
